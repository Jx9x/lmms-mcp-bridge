#!/usr/bin/perl
# Generates QtCore/qfeatures.h from qtbase's src/corelib/global/qfeatures.txt,
# following the algorithm in qtbase-5.4.2/qtbase.pro ("Generate qfeatures.h"):
# every feature with a non-empty "Requires:" line becomes
#   #if !defined(QT_NO_<F>) && (defined(QT_NO_<D1>) || defined(QT_NO_<D2>) ...)
#   #  define QT_NO_<F>
#   #endif
# emitted in dependency order (dependencies first) so cascades resolve in one pass.
#
# usage: perl gen_qfeatures.pl <qfeatures.txt> <output qfeatures.h>
use strict;
use warnings;

my ($in, $out) = @ARGV;
die "usage: $0 <qfeatures.txt> <qfeatures.h>\n" unless defined $in && defined $out;

open(my $fh, '<', $in) or die "cannot read $in: $!\n";
my (@order, %depends, $feature);
while (my $line = <$fh>) {
    $line =~ s/\r?\n$//;
    if ($line =~ /^Feature: (\S+)\s*$/) {
        $feature = $1;
        push @order, $feature;
        $depends{$feature} = [];
    } elsif (defined $feature && $line =~ /^Requires: (.*)$/) {
        (my $deps = $1) =~ s/\s+$//;
        $depends{$feature} = [ split ' ', $deps ];
    }
}
close $fh;

my (%state, @sorted);
sub visit {
    my ($f) = @_;
    return if ($state{$f} // 0) == 2;
    die "dependency cycle at $f\n" if ($state{$f} // 0) == 1;
    $state{$f} = 1;
    for my $d (@{ $depends{$f} // [] }) {
        die "feature $f requires unknown feature $d\n" unless exists $depends{$d};
        visit($d);
    }
    $state{$f} = 2;
    push @sorted, $f;
}
visit($_) for @order;

open(my $oh, '>', $out) or die "cannot write $out: $!\n";
print $oh "/*\n * All feature dependencies.\n *\n";
print $oh " * This list is generated by qmake from <qtbase>/src/corelib/global/qfeatures.txt\n */\n";
for my $f (@sorted) {
    my @d = @{ $depends{$f} };
    next unless @d;
    print $oh "#if !defined(QT_NO_$f) && (" . join(' || ', map { "defined(QT_NO_$_)" } @d) . ")\n";
    print $oh "#  define QT_NO_$f\n#endif\n";
}
close $oh;
printf "%d features, %d dependency rules written to %s\n",
    scalar(@order), scalar(grep { @{ $depends{$_} } } @order), $out;
